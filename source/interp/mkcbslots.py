#!/usr/bin/env python3
"""mkcbslots.py — generate interp/cb_slots.s, the callback trampoline pool.

WHY A POOL OF STUBS AT ALL. Native code is constantly handed arm64 function pointers — every block, every
   delegate method, every sort comparator — and it will CALL them. An arm64 address jumped to by x86 executes
   nonsense, so each guest function needs a distinct NATIVE address that leads back into the interpreter. The
   only thing distinguishing those addresses is which guest function they stand for, so each stub does exactly
   one thing: load its own index and jump to the common entry.

EVERY STUB IS THE SAME SIZE AND THE SIZE IS LOAD-BEARING: __arm2x86_cb returns base + 16 * index, so the
   .p2align 4 below is not cosmetic. A stub that grew past 16 bytes would silently hand out the wrong
   function's address.

The per-app runtime sized this pool at 2,048 and Cyberpunk exhausted it three seconds in, because every
   exact guest function start passed to a native pointer gets a slot. 131,072 slots is 2 MB of stubs — address
   space, paid for only as it is touched — and exhausting it still aborts BY NAME rather than reusing a slot.
"""
import os, sys

SLOTS = 1 << 17
HERE = os.path.dirname(os.path.abspath(__file__))

asm = f'''// GENERATED by interp/mkcbslots.py — do not edit.
// {SLOTS} trampolines, 16 bytes each: slot i loads i and jumps to the common entry.
.text
.p2align 4
.globl ___arm2x86_cb_slots
___arm2x86_cb_slots:
.set ___arm2x86_cbi, 0
.rept {SLOTS}
  movl $___arm2x86_cbi, %r11d
  jmp ___arm2x86_cb_common
  .p2align 4
  .set ___arm2x86_cbi, ___arm2x86_cbi+1
.endr

// The common entry keeps the native caller's argument registers, asks cb_prepare which guest function this
// slot stands for, then hands everything to the door.
// rax is a Swift caller's indirect-result pointer (arm64 x8) and r14 its async context: cb_prepare would
//    clobber both, so they are saved across it and passed to the door as stack arguments.
.p2align 4
.globl ___arm2x86_cb_common
___arm2x86_cb_common:
  .cfi_startproc
  pushq %rbp
  .cfi_def_cfa_offset 16
  .cfi_offset %rbp, -16
  movq %rsp, %rbp
  .cfi_def_cfa_register %rbp
  subq $208, %rsp
  movq %rax, 176(%rsp)
  movq %r14, 184(%rsp)
  movq %rdi, 0(%rsp)
  movq %rsi, 8(%rsp)
  movq %rdx, 16(%rsp)
  movq %rcx, 24(%rsp)
  movq %r8, 32(%rsp)
  movq %r9, 40(%rsp)
'''
asm += ''.join(f'  movdqu %xmm{i}, {48 + 16 * i}(%rsp)\n' for i in range(8))
asm += '''  movl %r11d, %edi
  movq 0(%rsp), %rsi
  movq 184(%rsp), %rdx
  movq %rbp, %rcx
  callq ___arm2x86_cb_prepare
  movq %rax, %r10
  movq %rdx, 192(%rsp)
'''
asm += '  movq 0(%rsp), %rdi\n  movq 8(%rsp), %rsi\n  movq 16(%rsp), %rdx\n  movq 24(%rsp), %rcx\n  movq 32(%rsp), %r8\n  movq 40(%rsp), %r9\n'
asm += ''.join(f'  movdqu {48 + 16 * i}(%rsp), %xmm{i}\n' for i in range(8))
asm += '''  movq 176(%rsp), %rax
  movq 184(%rsp), %r11
  subq $48, %rsp
  movq %r10, 0(%rsp)
  movq %rax, 8(%rsp)
  movq %r11, 16(%rsp)
  movq %r13, 24(%rsp)
  movq %r12, 32(%rsp)
  callq ___arm2x86_cb_door
  addq $48, %rsp
  movq 192(%rsp), %r11
  movq %rbp, %rsp
  popq %rbp
  testq %r11, %r11
  jnz 1f
  retq
1:
  retq $8
  .cfi_endproc
'''

# Nothing may be written back over the saved arguments after cb_prepare. A stray `movq %rdi, 0(%rsp)`
#    here replaced the saved a0 with a register cb_prepare had already clobbered, so the guest callback got a
#    garbage first argument — qsort's comparator then dereferenced it and the process took a bus error, with
#    nothing to say the stub had corrupted its own frame. The block at 0(%rsp)..40(%rsp) is read-only from
#    the call onward; only rax/r14, saved higher up, are re-loaded.
open(os.path.join(HERE, 'cb_slots.s'), 'w').write(asm)
print(f'cb_slots.s: {SLOTS} trampolines')
